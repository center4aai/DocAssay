# ---------------------------------------------------------------------------
# Phase 2 claim-gate — every predicate exposes a gate; non-claims never reach
# the verdict layer and carry a reason.
# ---------------------------------------------------------------------------


def _claim(predicate: str, object: str, raw_context: str) -> pipeline_mod.PredicateClaim:
    from docassay.core.models import PredicateClaim

    return PredicateClaim(
        claim_id="t",
        source="README.md",
        predicate_type=predicate,
        object=object,
        raw_context=raw_context,
        context=Context(),
    )


def test_all_predicates_expose_a_gate() -> None:
    for p in (
        "dependency_predicate",
        "path_exists_predicate",
        "symbol_exists_predicate",
        "license_predicate",
        "has_dockerfile_predicate",
        "has_ci_workflow_predicate",
    ):
        module, _, _ = p.partition("_predicate")
        pred = {
            "dependency": dep_mod,
            "path_exists": listing_mod,
            "symbol_exists": structure_mod,
            "license": xd,
            "has_dockerfile": infra_mod,
            "has_ci_workflow": infra_mod,
        }[module]
        assert callable(getattr(pred, p).gate), f"{p} lost its gate"


def test_gate_instructional_is_sentence_initial_only() -> None:
    # "The module defines X" describes current state — stays a claim.
    assert structure_mod.symbol_exists_gate(
        _claim("SYMBOL_EXISTS", "pylib.core", "The `pylib.core` module defines `render()`.")
    ).ok
    # Sentence-initial imperative is a directive — non-claim.
    assert not structure_mod.symbol_exists_gate(
        _claim("SYMBOL_EXISTS", "x", "Add a `parse` function to `pkg`.")
    ).ok


def test_historical_time_words_are_contextual() -> None:
    # d: "since"/"until" are historical only next to a version
    # or a date. "blocks until interrupted" is a present-state description and
    # must not be gated — the stale-symbol finding must survive.
    def gate(text: str, obj: str) -> bool:
        claim = next(
            c for c in structure_mod.symbol_exists_scan(text, "README.md") if c.object == obj
        )
        return structure_mod.symbol_exists_gate(claim).ok

    assert gate(
        "The `pkg.old_module.helper()` function blocks until interrupted.\n",
        "pkg.old_module.helper",
    )
    # "until v3" is a genuine past/cease boundary.
    assert not gate("`pkg.old_module.helper()` was supported until v3.\n", "pkg.old_module.helper")
    # "since 2.0" — historical; bare causal "since" — not.
    assert not gate("`pkg.f` has existed since 2.0.\n", "pkg.f")
    assert gate("`pkg.f` has existed since the beginning.\n", "pkg.f")


def test_dropped_is_historical_verb_form() -> None:
    # : "was dropped" is a past-state mention ("setup.py was
    # dropped in favour of pyproject.toml"), not a current existence claim.
    claim = next(
        c
        for c in listing_mod.path_exists_scan(
            "The `setup.py` script was dropped in favour of `pyproject.toml`.\n", "README.md"
        )
        if c.object == "setup.py"
    )
    assert not listing_mod.path_exists_gate(claim).ok


def test_gate_form_signals() -> None:
    # Placeholder / extensionless-slash anchors are non-claims by form.
    assert not listing_mod.path_exists_gate(
        _claim("PATH_EXISTS", "version-x.x.x/", "the `version-x.x.x/` directory")
    ).ok
    assert not listing_mod.path_exists_gate(
        _claim("PATH_EXISTS", "gzip/bz2", "tools like `gzip/bz2`")
    ).ok
    # A last-segment host TLD is NOT gated anymore: real symbols whose last
    # segment is an IANA TLD (``typer.run``, ``pytest.fail``, ``numpy.save``)
    # would be dropped. The match layer abstains only on an *unresolved*
    # TLD-ending claim.
    assert structure_mod.symbol_exists_gate(
        _claim("SYMBOL_EXISTS", "docs.sqlfluff.com", "see `docs.sqlfluff.com`")
    ).ok


def test_gate_dependency_surgical_scope() -> None:
    from docassay.core.models import PredicateClaim

    # Versionless negation stays a verdict-layer claim (conservative NEI), it is
    # NOT gated — the inventory's absence cannot settle a usage negation.
    assert dep_mod.dependency_gate(
        _claim("DEPENDENCY", "numpy", "The project does not use numpy.")
    ).ok
    # A hypothetical WITHOUT a negation ("if the package is installed") is a
    # condition, not a non-claim; a genuine hypothetical negation is gated.
    assert dep_mod.dependency_gate(
        _claim("DEPENDENCY", "redis", "If the package is installed, it is used.")
    ).ok
    negated = PredicateClaim(
        claim_id="t",
        source="README.md",
        predicate_type="DEPENDENCY",
        object="redis",
        raw_context="If you have not installed redis.",
        context=Context(polarity=frozenset({"not"})),
    )
    assert not dep_mod.dependency_gate(negated).ok
    # Historical mentions are non-claims.
    assert not dep_mod.dependency_gate(
        _claim("DEPENDENCY", "redis", "redis was removed in an earlier release.")
    ).ok


def test_claim_gate_reasons_name_the_cue() -> None:
    # Every downgrade names the cue that fired, not a generic label.
    from docassay.core.models import PredicateClaim
    from docassay.predicates.dependency import config_fragment_reason

    cases = {
        "historical": "historical mention",
        "instructional": "instruction",
        "exemplary": "example",
        "user_config": "user runtime config",
        "reader_space": "reader's own file",
        "reader_file": "reader's own file",
        "generated": "generated file",
    }
    for flag, reason in cases.items():
        verdict = listing_mod.path_exists_match("src/gone.py", Context(), {}, **{flag: True})
        assert (verdict.layer, verdict.reason) == ("CLAIM_GATE", reason), flag

    def claim(raw: str) -> PredicateClaim:
        return PredicateClaim(
            claim_id="c1",
            predicate_type="DEPENDENCY",
            object="pytest",
            context=Context(),
            source="README.md",
            raw_context=raw,
        )

    assert config_fragment_reason(claim('pytest = "^8.0.0"')) == "key = value fragment"
    assert config_fragment_reason(claim('"pytest (>=8.0.0,<9.0.0)",')) == (
        "quoted requirement string"
    )
    assert config_fragment_reason(claim("The tests run with pytest 8.")) == ""
