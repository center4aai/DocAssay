"""Abstention-rule invariants: documented NEI rules must exist in the code.

Every rule registered in the abstention rules (§1 non-extraction, §2 verdict
layer, §4 triage gap) is bound to a concrete function/signal in
``src/``. These tests freeze that binding so a refactor that drops a rule, or a
doc edit that invents one, fails loudly — mirroring
``test_vocabulary_integrity.py``'s role for the vocabularies.

This module guards the *existence and wiring* of the rules, not the exact
word lists (those live in ``data/*.json`` and are regenerated by
``the internal vocabulary build script (not shipped)``).
"""

