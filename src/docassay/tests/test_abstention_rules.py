def test_genre_gate_is_per_claim_not_per_assertion() -> None:
    """F3 / : a plan-document claim must not refute on its own, but a
    non-genre claim sharing the same context-cluster keeps the finding REFUTED."""
    from docassay.core.models import Assertion, Context, PredicateClaim

    def claim(source: str) -> PredicateClaim:
        return PredicateClaim(
            claim_id=f"{source}:1:1",
            source=source,
            predicate_type="DEPENDENCY",
            object="python",
            raw_context="Python 2.7",
            context=Context(version="2.7"),
            line_start=1,
            line_end=1,
        )

    ev = {
        "python": [
            DependencyEvidence(
                evidence_id="p:pyproject.toml",
                package_name="python",
                version_spec=">=3.10",
                source_file="pyproject.toml",
                source_type="main",
            )
        ]
    }
    genre = {"doc/neps/nep-0014.rst"}

    mixed = Assertion(
        predicate_type="DEPENDENCY",
        object="python",
        domain="",
        claims=(claim("doc/neps/nep-0014.rst"), claim("README.md")),
        context=Context(version="2.7"),
    )
    only_genre = Assertion(
        predicate_type="DEPENDENCY",
        object="python",
        domain="",
        claims=(claim("doc/neps/nep-0014.rst"),),
        context=Context(version="2.7"),
    )
    adj = pipeline_mod._adjudicate_assertion
    mixed_r = adj(mixed, dep_mod.dependency_predicate, ev, {}, True, genre)
    only_r = adj(only_genre, dep_mod.dependency_predicate, ev, {}, True, genre)

    assert mixed_r.code_verdict == "REFUTED"  # non-genre claim still refutes
    assert only_r.code_verdict == "NEI"  # genre-only refutation abstains
    assert only_r.code_verdict_layer == "CLAIM_GATE"


