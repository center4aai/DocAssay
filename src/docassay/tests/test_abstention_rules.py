def test_calibration_rules_are_known_and_binding() -> None:
    """gold.jsonl rules must use the three-axis vocabulary (the abstention rules
    §3); REFUTED->NEI must be a gap class (CLAIM:GAP:*/DECID:GAP:*, rule absent
    from the verdict layer, §4)."""
    import json
    from pathlib import Path

    gold_path = Path(__file__).resolve().parents[3] / "research" / "calibration" / "gold.jsonl"
    if not gold_path.exists():
        return  # calibration is a research artifact; guard is advisory
    records = [json.loads(line) for line in gold_path.open(encoding="utf-8")]
    known = re.compile(r"^(?:S|R|(?:CLAIM|WORLD|DECID)(?::GAP)?:[a-z-]+)$")
    for r in records:
        assert known.match(r.get("rule", "")), f"bad rule {r.get('rule')!r}: {r['sample_id']}"
    for r in records:
        if r["tool_verdict"] == "REFUTED" and r["gold_verdict"] == "NEI":
            assert ":GAP:" in r["rule"], (
                f"REFUTED->NEI must be a gap class (CLAIM:GAP:* / DECID:GAP:*), "
                f"got {r['rule']!r} ({r['sample_id']})"
            )


# ---------------------------------------------------------------------------
# 3-layer model — every NEI carries a WORLD / DECIDABILITY / CLAIM_GATE layer
# ---------------------------------------------------------------------------

_NEI_LAYERS = frozenset({"WORLD", "DECIDABILITY", "CLAIM_GATE"})
_RESOLVED_HINTS = ("class/attribute name matches only a module", "case differs:")


def _assert_verdict_layered(result, allowed: frozenset[str]) -> None:
    """SUPPORTED/REFUTED carry no layer; NEI must carry one of `allowed` + reason."""
    if result.outcome == "NEI":
        assert result.layer in allowed, f"NEI outside allowed layers {sorted(allowed)}: {result}"
        assert result.reason, f"NEI without a reason: {result}"
    else:
        assert result.outcome in {"SUPPORTED", "REFUTED"}
        assert result.layer == "", f"non-NEI {result.outcome} carried a layer: {result}"
        # A resolved verdict may carry only a hint, never a gate/abstention reason.
        assert result.reason == "" or result.reason.startswith(_RESOLVED_HINTS), (
            f"non-NEI {result.outcome} carried a reason: {result}"
        )


def test_dependency_nei_layers() -> None:
    # D1: undeclared dependency — OPEN-by-transitivity (WORLD).
    _assert_verdict_layered(dep_mod.match_dependency("redis", Context(), {}), {"WORLD"})
    # D2/P1: negation with no evidence — conservative (WORLD).
    _assert_verdict_layered(
        dep_mod.match_dependency("redis", Context(polarity=frozenset({"not"})), {}),
        {"WORLD"},
    )
    # D7: declared but no version spec — not decidable (DECIDABILITY).
    ev = {
        "redis": [
            DependencyEvidence(
                evidence_id="r:pyproject.toml",
                package_name="redis",
                version_spec="",
                source_file="pyproject.toml",
                source_type="main",
            )
        ]
    }
    _assert_verdict_layered(
        dep_mod.match_dependency("redis", Context(version="3.0"), ev),
        {"DECIDABILITY"},
    )


